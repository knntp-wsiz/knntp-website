import type { Messages } from "@/i18n/messages";

export type CourseId = keyof Messages["courses"]["items"];

export type CourseTopic = "programming" | "ai";

export type CourseLevel = "beginner" | "intermediate" | "advanced";

/** Cena samego kursu lub egzaminu. */
export type CoursePrice = "free" | "paid";

/** none: brak certyfikatu; free: bezpłatny (także odznaka ukończenia); paid: płatny. */
export type CourseCertificate = "none" | "free" | "paid";

export type Course = {
	id: CourseId;
	/** Nazwa własna, taka sama w obu językach. */
	name: string;
	kind: "course" | "exam";
	topic: CourseTopic;
	/** Tylko gdy poziom podaje źródło. */
	level?: CourseLevel;
	price: CoursePrice;
	certificate: CourseCertificate;
	/** Kwota podana przez organizatora, jeśli jest na jego stronie. */
	cost?: string;
	hours?: number;
	provider: string;
	/** Oficjalna strona kursu lub egzaminu. */
	url: string;
	languages: string[];
	/** Okładka; ścieżka w public/. */
	cover: string;
};

